const FETCH_BOOKS_ERROR = "Không thể tải danh sách sách. Vui lòng thử lại."

export function fetchBooks(
  options: FetchBooksOptions = {}
): Promise<ApiResult<Book[]>> {
  const { fail = false, delayMs = FETCH_DELAY_MS } = options
  return new Promise((resolve) => {
    setTimeout(() => {
      resolve(
        fail
          ? { ok: false, error: FETCH_BOOKS_ERROR }
          : { ok: true, data: SEED_BOOKS.map((book) => ({ ...book })) }
      )
    }, delayMs)
  })
}
